"""Generate the edge Worker's shared constants from the Python source of truth, and copy the compiled page.
Run from anywhere:  python3 deploy/cloudflare-edge/build_edge.py
"""
import json
import shutil
import sys
from pathlib import Path

EDGE = Path(__file__).resolve().parent
ROOT = EDGE.parents[1]
sys.path.insert(0, str(ROOT))
from atlas_voice.quality import FIELDS, INTERVIEW_POLICY, NUMERIC, TO_TOPIC, UNCERTAIN, UNKNOWN  # noqa: E402
from atlas_voice.analyst import ANALYST_POLICY, CHAT_TOOLS, CONTEXT_SEGMENTS, SEGMENT_CHARS, MAX_CALLS  # noqa: E402
from atlas_voice.cascade import TALKER_POLICY, OPENING, HISTORY, ADMIN_NOTE, SPEAKING_LIMIT_S, INTERVIEW_LIMIT_S, WRAP_S, TIME_UP, AREAS  # noqa: E402
from atlas_voice.interview import TOPICS  # noqa: E402
from atlas_voice.report import END_TOKEN, REPORT_POLICY, REPORT_TOPICS, REPORT_LIMITS, REPORT_LISTS, REPORT_TRANSCRIPT_CHARS, FACT_TEXT, FACT_LISTS  # noqa: E402

constants = {
    'INTERVIEW_POLICY': INTERVIEW_POLICY, 'TALKER_POLICY': TALKER_POLICY, 'OPENING': OPENING, 'HISTORY': HISTORY, 'ADMIN_NOTE': ADMIN_NOTE, 'SPEAKING_LIMIT_S': SPEAKING_LIMIT_S, 'INTERVIEW_LIMIT_S': INTERVIEW_LIMIT_S, 'WRAP_S': WRAP_S, 'TIME_UP': TIME_UP, 'AREAS': list(AREAS),
    'ANALYST_POLICY': ANALYST_POLICY, 'CHAT_TOOLS': CHAT_TOOLS, 'CONTEXT_SEGMENTS': CONTEXT_SEGMENTS,
    'SEGMENT_CHARS': SEGMENT_CHARS, 'MAX_CALLS': MAX_CALLS, 'FIELDS': FIELDS, 'TO_TOPIC': TO_TOPIC, 'TOPICS': TOPICS,
    'END_TOKEN': END_TOKEN, 'REPORT_POLICY': REPORT_POLICY, 'REPORT_TOPICS': list(REPORT_TOPICS), 'REPORT_LIMITS': REPORT_LIMITS,
    'REPORT_LISTS': REPORT_LISTS, 'REPORT_TRANSCRIPT_CHARS': REPORT_TRANSCRIPT_CHARS, 'FACT_TEXT': FACT_TEXT, 'FACT_LISTS': FACT_LISTS,
    'NUMERIC_SRC': NUMERIC.pattern, 'UNCERTAIN_SRC': UNCERTAIN.pattern, 'UNKNOWN_SRC': UNKNOWN.pattern,
}
def render():
    lines = ['// GENERATED by build_edge.py from atlas_voice/*.py. Do not edit; regenerate instead.']
    lines += [f'export const {k} = {json.dumps(v, ensure_ascii=False)};' for k, v in constants.items()]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    (EDGE / 'src' / 'policy.generated.js').write_text(render())
    shutil.copyfile(ROOT / 'ATLAS_Voice.html', EDGE / 'src' / 'atlas.html')
    print('edge constants + page generated')
