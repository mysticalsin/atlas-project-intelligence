"""Generate the edge Worker's shared constants from the Python source of truth, and copy the compiled page.
Run from anywhere:  python3 deploy/cloudflare-edge/build_edge.py
                    python3 deploy/cloudflare-edge/build_edge.py --policy-only   (constants only; the page is not copied)
"""
import importlib
import json
import shutil
import sys
from pathlib import Path

EDGE = Path(__file__).resolve().parent
ROOT = EDGE.parents[1]
sys.path.insert(0, str(ROOT))
from atlas_voice.quality import FIELDS, INTERVIEW_POLICY, NUMERIC, TO_TOPIC, UNCERTAIN, UNKNOWN  # noqa: E402
from atlas_voice.analyst import ANALYST_POLICY, CHAT_TOOLS, CONTEXT_SEGMENTS, SEGMENT_CHARS, MAX_CALLS  # noqa: E402
from atlas_voice.cascade import TALKER_POLICY, OPENING, HISTORY, ADMIN_NOTE, SPEAKING_LIMIT_S, INTERVIEW_LIMIT_S, WRAP_S, TIME_UP, AREAS, TIME_UP_MESSAGE  # noqa: E402
from atlas_voice.gaps import (GAP_LIMIT_S, GAP_SPEAKING_S, GAP_WRAP_S, GAP_MAX, GAP_ATTEMPTS, GAP_ANSWER_WORDS, TIME_PLAN, GAP_LIST_LABEL,  # noqa: E402
                              GAP_NOTE, GAP_OPENING, GAP_WHY, GAP_DONE_WHY, GAP_REFLECT, WIN_HINTS)
from atlas_voice.interview import TOPICS  # noqa: E402
from atlas_voice.report import END_TOKEN, REPORT_POLICY, REPORT_TOPICS, REPORT_LIMITS, REPORT_LISTS, REPORT_TRANSCRIPT_CHARS, FACT_TEXT, FACT_LISTS  # noqa: E402

constants = {
    'INTERVIEW_POLICY': INTERVIEW_POLICY, 'TALKER_POLICY': TALKER_POLICY, 'OPENING': OPENING, 'HISTORY': HISTORY, 'ADMIN_NOTE': ADMIN_NOTE, 'SPEAKING_LIMIT_S': SPEAKING_LIMIT_S, 'INTERVIEW_LIMIT_S': INTERVIEW_LIMIT_S, 'WRAP_S': WRAP_S, 'TIME_UP': TIME_UP, 'AREAS': list(AREAS),
    'ANALYST_POLICY': ANALYST_POLICY, 'CHAT_TOOLS': CHAT_TOOLS, 'CONTEXT_SEGMENTS': CONTEXT_SEGMENTS,
    'SEGMENT_CHARS': SEGMENT_CHARS, 'MAX_CALLS': MAX_CALLS, 'FIELDS': FIELDS, 'TO_TOPIC': TO_TOPIC, 'TOPICS': TOPICS,
    'END_TOKEN': END_TOKEN, 'REPORT_POLICY': REPORT_POLICY, 'REPORT_TOPICS': list(REPORT_TOPICS), 'REPORT_LIMITS': REPORT_LIMITS,
    'REPORT_LISTS': REPORT_LISTS, 'REPORT_TRANSCRIPT_CHARS': REPORT_TRANSCRIPT_CHARS, 'FACT_TEXT': FACT_TEXT, 'FACT_LISTS': FACT_LISTS,
    'NUMERIC_SRC': NUMERIC.pattern, 'UNCERTAIN_SRC': UNCERTAIN.pattern, 'UNKNOWN_SRC': UNKNOWN.pattern,
    'GAP_LIMIT_S': GAP_LIMIT_S, 'GAP_SPEAKING_S': GAP_SPEAKING_S, 'GAP_WRAP_S': GAP_WRAP_S, 'GAP_MAX': GAP_MAX, 'GAP_ATTEMPTS': GAP_ATTEMPTS,
    'GAP_ANSWER_WORDS': GAP_ANSWER_WORDS, 'TIME_PLAN': TIME_PLAN, 'GAP_LIST_LABEL': GAP_LIST_LABEL, 'GAP_NOTE': GAP_NOTE, 'GAP_OPENING': GAP_OPENING,
    'GAP_WHY': GAP_WHY, 'GAP_DONE_WHY': GAP_DONE_WHY, 'GAP_REFLECT': GAP_REFLECT, 'WIN_HINTS': WIN_HINTS, 'TIME_UP_MESSAGE': TIME_UP_MESSAGE,
}
# Later modules register here, one line each. A module may expose EDGE_CONSTANTS (a dict) that is merged after the
# constants above; a key defined twice is an error rather than a silent override.
EDGE_MODULES = [
    'atlas_voice.workflow_config',
    'atlas_voice.conversation_state',
    'atlas_voice.turns',
    'atlas_voice.persona',
    'atlas_voice.success_story',
    'atlas_voice.selector',
    'atlas_voice.asr',
    'atlas_voice.connections_config',
]
for _name in EDGE_MODULES:
    for _key, _value in getattr(importlib.import_module(_name), 'EDGE_CONSTANTS', {}).items():
        if _key in constants:
            raise ValueError(f'{_name} redefines edge constant {_key}')
        constants[_key] = _value


def render():
    lines = ['// GENERATED by build_edge.py from atlas_voice/*.py. Do not edit; regenerate instead.']
    lines += [f'export const {k} = {json.dumps(v, ensure_ascii=False)};' for k, v in constants.items()]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    (EDGE / 'src' / 'policy.generated.js').write_text(render())
    if '--policy-only' in sys.argv[1:]:
        print('edge constants generated (page not copied)')
    else:
        shutil.copyfile(ROOT / 'ATLAS_Voice.html', EDGE / 'src' / 'atlas.html')
        print('edge constants + page generated')
