#!/usr/bin/env python3
"""Vendor @microsoft/teams-js 2.57.0 (MIT) for the Teams launcher tab (WOW_SPEC F4.6). Standard library only; no network.

    npm pack @microsoft/teams-js@2.57.0            # anywhere; npm checks the registry integrity (sha512)
    python3 deploy/cloudflare-edge/teams/vendor_teamsjs.py microsoft-teams-js-2.57.0.tgz

Accepts the npm tarball (checked against the pinned registry sha512 integrity, then dist/umd/MicrosoftTeams.min.js is
read from it) or the MicrosoftTeams.min.js file itself (checked against the pinned SHA-256). Writes
teams/vendor/teams-js.mjs, which embeds the bundle byte for byte as a JS string, and the package LICENSE next to it.
Refuses anything that does not match the pins, or that could end an inline <script> element.
"""
import base64
import hashlib
import json
import sys
import tarfile
from pathlib import Path

VERSION = '2.57.0'
TGZ_INTEGRITY = 'sha512-HJPyDD52nzs5E4WeScncMWHBDOQTSjtF1s3QFYTEGqVp+yqgRAJ1nTrcHyYw9TARKFg8y05OQLCOSRqM656wQw=='
MIN_JS_SHA256 = 'ee3403839e47f1338e6f6f8becdd4456ced589eca5a909b8e58ce31ff78cf068'
MEMBER = 'package/dist/umd/MicrosoftTeams.min.js'
VENDOR = Path(__file__).resolve().parent / 'vendor'


def load(path):
    data = Path(path).read_bytes()
    license_text = None
    if data[:2] == b'\x1f\x8b':
        got = 'sha512-' + base64.b64encode(hashlib.sha512(data).digest()).decode()
        if got != TGZ_INTEGRITY:
            raise SystemExit(f'Refused: the tarball integrity {got} is not the pinned {TGZ_INTEGRITY}.')
        with tarfile.open(path, 'r:gz') as t:
            data = t.extractfile(MEMBER).read()
            license_text = t.extractfile('package/LICENSE').read().decode('utf-8')
    digest = hashlib.sha256(data).hexdigest()
    if digest != MIN_JS_SHA256:
        raise SystemExit(f'Refused: MicrosoftTeams.min.js SHA-256 {digest} is not the pinned {MIN_JS_SHA256}.')
    text = data.decode('utf-8')
    if '</script' in text.lower() or '<!--' in text or ' ' in text or ' ' in text:
        raise SystemExit('Refused: the bundle cannot be inlined safely in a <script> element.')
    return text, license_text


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    text, license_text = load(argv[1])
    VENDOR.mkdir(parents=True, exist_ok=True)
    (VENDOR / 'teams-js.mjs').write_bytes((
        f'// GENERATED by teams/vendor_teamsjs.py from @microsoft/teams-js {VERSION} (MIT, see LICENSE-teams-js.txt):\n'
        f'// dist/umd/MicrosoftTeams.min.js, byte for byte (SHA-256 {MIN_JS_SHA256}). Do not edit.\n'
        f"export const TEAMS_JS_VERSION = '{VERSION}';\n"
        f"export const TEAMS_JS_SHA256 = '{MIN_JS_SHA256}';\n"
        f'export const TEAMS_JS = {json.dumps(text, ensure_ascii=False)};\n').encode('utf-8'))
    if license_text:
        (VENDOR / 'LICENSE-teams-js.txt').write_bytes(license_text.encode('utf-8'))
    print(f'Vendored @microsoft/teams-js {VERSION} ({len(text.encode())} bytes, SHA-256 {MIN_JS_SHA256}).')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
